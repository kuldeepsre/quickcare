  /// Load language from secure device storage on app startup
  Future<void> loadSavedLanguage() async {
    try {
      final savedLang = await _secureStorage.read(key: _languageKey);
      if (savedLang != null && _localizedStrings.containsKey(savedLang)) {
        _currentLanguage = savedLang;
        notifyListeners();
      }
    } catch (e) {
      // Fallback in case secure storage fails on simulator/device initialization
      debugPrint('Error reading secure storage: $e');
    }
  }

  /// Change language and save to secure device storage
  Future<void> setLanguage(String lang) async {
    if (_localizedStrings.containsKey(lang) && _currentLanguage != lang) {
      _currentLanguage = lang;
      notifyListeners();

      try {
        await _secureStorage.write(key: _languageKey, value: lang);
      } catch (e) {
        debugPrint('Error writing to secure storage: $e');
      }
    }
  }

  String translate(String key) {
    return _localizedStrings[_currentLanguage]?[key] ?? _localizedStrings['English']![key]!;
  }
